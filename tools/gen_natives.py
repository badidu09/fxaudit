#!/usr/bin/env python3
"""Regenerates src/fxaudit/data/natives.lua from the official natives database.

Usage: python tools/gen_natives.py [natives.json natives_cfx.json]
Without arguments the two files are downloaded from runtime.fivem.net.

Only native names and the side they exist on are kept. Names follow the Lua
binding convention: GET_PLAYER_PED becomes GetPlayerPed.
"""
import json
import os
import sys
import urllib.request

BASE = "https://runtime.fivem.net/doc/"
OUTPUT = os.path.join(os.path.dirname(__file__), "..", "src", "fxaudit", "data", "natives.lua")


def load(path_or_name):
    if os.path.exists(path_or_name):
        with open(path_or_name, encoding="utf8") as handle:
            return json.load(handle)
    with urllib.request.urlopen(BASE + path_or_name) as response:
        return json.load(response)


def lua_name(native_name):
    return "".join(part[:1].upper() + part[1:].lower() for part in native_name.split("_") if part)


def collect(database, default_side, sides):
    for namespace in database.values():
        for native in namespace.values():
            side = native.get("apiset") or default_side
            for name in [native.get("name", "")] + list(native.get("aliases") or []):
                if name and not name.startswith("0x"):
                    sides.setdefault(side, set()).add(lua_name(name))


def wrap(names):
    lines, line = [], ""
    for name in sorted(names):
        if len(line) + len(name) > 110:
            lines.append(line.rstrip())
            line = ""
        line += name + " "
    lines.append(line.rstrip())
    return "\n".join(lines)


def main():
    files = sys.argv[1:] or ["natives.json", "natives_cfx.json"]
    sides = {}
    collect(load(files[0]), "client", sides)
    collect(load(files[1]), "client", sides)
    with open(OUTPUT, "w", encoding="utf8", newline="\n") as out:
        out.write("-- Generated by tools/gen_natives.py. Do not edit by hand.\n")
        out.write("return {\n")
        for side in ("client", "server", "shared"):
            out.write(f"{side} = [[\n{wrap(sides.get(side, []))}\n]],\n")
        out.write("}\n")
    print({side: len(names) for side, names in sides.items()})


if __name__ == "__main__":
    main()
