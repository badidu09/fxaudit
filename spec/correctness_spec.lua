local t = require("spec.harness")
local S = require("spec.support")

t.describe("correctness", function()
  t.it("FX300 flags self-comparison but keeps the NaN idiom", function()
    t.eq(S.count("FX300", "local a = {}\nif a.b == a.b then end"), 1)
    t.eq(S.count("FX300", "local a = 1\nif a == a then end"), 0)
    t.eq(S.count("FX300", "local a = 1\nif a ~= a then end"), 0)
    t.eq(S.count("FX300", "if f() == f() then end\nfunction f() end"), 0)
  end)

  t.it("FX301 flags duplicate keys", function()
    t.eq(S.count("FX301", "local t = { a = 1, a = 2, ['b'] = 1, b = 2, [1] = 1, [1] = 2 }\nprint(t)"), 3)
    t.eq(S.count("FX301", "local t = { a = 1, b = 2, 3, 4 }\nprint(t)"), 0)
  end)

  t.describe("FX302 unreachable-code", function()
    t.it("flags code after break, goto and error", function()
      t.eq(S.count("FX302", "while x do break print(1) end\nx = 1"), 1)
      t.eq(S.count("FX302", "error('a')\nprint(1)"), 1)
      t.eq(S.count("FX302", "local function f() error('a') return end\nf()"), 0)
    end)

    t.it("flags code after an infinite loop", function()
      t.eq(S.count("FX302", "while true do Wait(0) end\nprint(1)"), 1)
    end)

    t.it("accepts loops that can exit", function()
      t.eq(S.count("FX302", "while true do if a then break end end\nprint(1)\na = 1"), 0)
      t.eq(S.count("FX302", "while true do for i = 1, 2 do print(i) break end end\nprint(1)"), 1)
    end)

    t.it("accepts a label after a jump", function()
      t.eq(S.count("FX302", "goto a\n::a::\nprint(1)"), 0)
    end)
  end)

  t.it("FX303 flags empty blocks unless commented", function()
    t.eq(S.count("FX303", "local a\nif a then end"), 1)
    t.eq(S.count("FX303", "local a\nif a then\n-- later\nend"), 0)
    t.eq(S.count("FX303", "for i = 1, 2 do end"), 1)
  end)

  t.it("FX304 flags count mismatches", function()
    t.eq(S.count("FX304", "local a, b = 1\nprint(a, b)"), 1)
    t.eq(S.count("FX304", "local a = 1, 2\nprint(a)"), 1)
    t.eq(S.count("FX304", "local a, b = f()\nprint(a, b)\nfunction f() end"), 0)
    t.eq(S.count("FX304", "local a, b\nprint(a, b)"), 0)
  end)

  t.it("FX305 flags constant conditions", function()
    t.eq(S.count("FX305", "if true then print(1) end"), 1)
    t.eq(S.count("FX305", "while false do print(1) end"), 1)
    t.eq(S.count("FX305", "while true do Wait(0) end"), 0)
  end)

  t.it("FX306 flags too many arguments to a local function", function()
    t.eq(S.count("FX306", "local function f(a) return a end\nf(1, 2)"), 1)
    t.eq(S.count("FX306", "local function f(a) return a end\nf(1)"), 0)
    t.eq(S.count("FX306", "local function f(...) return ... end\nf(1, 2)"), 0)
    t.eq(S.count("FX306", "local function f(a) return a end\nf(1, g())\nfunction g() end"), 0)
  end)

  t.it("FX307 flags repeated elseif conditions", function()
    t.eq(S.count("FX307", "local a = 1\nif a == 1 then print(1) elseif a == 1 then print(2) end"), 1)
    t.eq(S.count("FX307", "local a = 1\nif a == 1 then print(1) elseif a == 2 then print(2) end"), 0)
  end)

  t.it("FX308 flags self-assignment", function()
    t.eq(S.count("FX308", "local a = 1\na = a"), 1)
    t.eq(S.count("FX308", "local a = a"), 0)
  end)

  t.it("FX309 flags a zero step", function()
    t.eq(S.count("FX309", "for i = 1, 2, 0 do print(i) end"), 1)
  end)

  t.it("FX310 flags impossible literal operations", function()
    t.eq(S.count("FX310", "print('a' .. nil)"), 1)
    t.eq(S.count("FX310", "print(1 + true)"), 1)
    t.eq(S.count("FX310", "print(#1)"), 1)
    t.eq(S.count("FX310", "print('a' .. 1)"), 0)
  end)

  t.it("FX311 flags 'not a == b'", function()
    t.eq(S.count("FX311", "local a, b = 1, 2\nif not a == b then print(1) end"), 1)
    t.eq(S.count("FX311", "local a, b = 1, 2\nif not (a == b) then print(1) end"), 0)
  end)

  t.it("FX312 flags removal in a forward loop", function()
    t.eq(S.count("FX312", "local t = {}\nfor i = 1, #t do table.remove(t, i) end"), 1)
    t.eq(S.count("FX312", "local t = {}\nfor i = #t, 1, -1 do table.remove(t, i) end"), 0)
    t.eq(S.count("FX312", "local t = {}\nfor i = 1, #t do if t[i] then table.remove(t, i) break end end"), 0)
    t.eq(S.count("FX312", "local t = {}\nfor i = 1, #t do if t[i] then table.remove(t, i) end end"), 1)
  end)

  t.it("FX313 flags 'x == a or \"b\"'", function()
    t.eq(S.count("FX313", "local x = 1\nif x == 'a' or 'b' then print(1) end"), 1)
    t.eq(S.count("FX313", "local x = 1\nif x == 'a' or x == 'b' then print(1) end"), 0)
    t.eq(S.count("FX313", "local x, y = 1, 2\nlocal z = (x == y) and 1 or 'b'\nprint(z)"), 0)
  end)

  t.it("FX314 flags missing format arguments", function()
    t.eq(S.count("FX314", "print(string.format('%s %d', 1))"), 1)
    t.eq(S.count("FX314", "print(string.format('%s %%', 1))"), 0)
    t.eq(S.count("FX314", "print(string.format('%s %s', ...))"), 0)
  end)
end)
